"""Generate src/gitsense/web/js/icons.js from the Lucide icon set.

Usage: python tools/gen_icons.py /path/to/lucide-static/icons
Get the icons with `npm pack lucide-static` and unpack the tarball.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ICONS = """
git-branch git-commit-horizontal git-merge git-pull-request git-pull-request-draft git-graph
git-compare tag archive archive-restore arrow-down-to-line arrow-up-from-line refresh-cw plus
minus x check chevron-right chevron-down search settings folder folder-open folder-git-2
folder-plus folder-search terminal external-link file file-plus file-minus file-diff trash-2
undo-2 copy sun moon monitor cloud laptop circle-dot ellipsis triangle-alert info star eye
filter list columns-2 rows-2 arrow-up arrow-down history pencil loader-circle house
layout-grid cherry clock link lock wrap-text circle-alert circle-check download square-pen
layers merge globe user corner-down-right rotate-ccw scissors palette swatch-book pipette upload
folders folder-minus list-checks
""".split()


def main() -> int:
    src = Path(sys.argv[1])
    out = Path(__file__).resolve().parent.parent / "src/gitsense/web/js/icons.js"
    entries = []
    for name in sorted(set(ICONS)):
        svg = (src / f"{name}.svg").read_text(encoding="utf-8")
        inner = svg.split(">", 2)[2] if svg.lstrip().startswith("<!--") else svg.split(">", 1)[1]
        inner = inner.rsplit("</svg>", 1)[0]
        inner = re.sub(r"\s+", " ", inner).replace(" />", "/>").replace("> <", "><").strip()
        entries.append(f"  {name!r}: {inner!r},")
    body = "\n".join(entries)
    out.write_text(
        "// GENERATED by tools/gen_icons.py from Lucide (https://lucide.dev), ISC license.\n"
        "// See web/LICENSE-lucide.txt. Do not edit by hand.\n\n"
        f"const PATHS = {{\n{body}\n}};\n\n"
        "/** Return an inline SVG element for a Lucide icon name. */\n"
        "export function icon(name, size = 16, cls = '') {\n"
        "  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');\n"
        "  svg.setAttribute('viewBox', '0 0 24 24');\n"
        "  svg.setAttribute('width', size);\n"
        "  svg.setAttribute('height', size);\n"
        "  svg.setAttribute('fill', 'none');\n"
        "  svg.setAttribute('stroke', 'currentColor');\n"
        "  svg.setAttribute('stroke-width', '2');\n"
        "  svg.setAttribute('stroke-linecap', 'round');\n"
        "  svg.setAttribute('stroke-linejoin', 'round');\n"
        "  svg.setAttribute('aria-hidden', 'true');\n"
        "  svg.setAttribute('class', `icon ${cls}`.trim());\n"
        "  svg.innerHTML = PATHS[name] || PATHS['circle-alert'];\n"
        "  return svg;\n"
        "}\n\n"
        "export const ICON_NAMES = Object.keys(PATHS);\n",
        encoding="utf-8",
    )
    print(f"wrote {out} ({len(entries)} icons)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
